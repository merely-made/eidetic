//! The resolved note's text: each lock under a `# ---- <path>` header.

/// The header line's prefix; the path follows it.
pub const HEADER: &str = "# ---- ";

/// Joins locks, in the order given, into the note's text. Each lock's bytes
/// follow its header unchanged, as the shell script's `cat` wrote them.
pub fn assemble(locks: &[(String, Vec<u8>)]) -> Vec<u8> {
    let mut note = Vec::new();
    for (path, bytes) in locks {
        note.extend_from_slice(HEADER.as_bytes());
        note.extend_from_slice(path.as_bytes());
        note.push(b'\n');
        note.extend_from_slice(bytes);
    }
    note
}

/// Splits a note back into (path, lock text). Text before the first header
/// is ignored.
pub fn split(note: &str) -> Vec<(String, String)> {
    let mut locks: Vec<(String, String)> = Vec::new();
    for line in note.split_inclusive('\n') {
        let bare = line.trim_end_matches(['\n', '\r']);
        if let Some(path) = bare.strip_prefix(HEADER) {
            locks.push((path.to_string(), String::new()));
        } else if let Some((_, text)) = locks.last_mut() {
            text.push_str(line);
        }
    }
    locks
}

/// Whether a path from a note is safe to write under the repository root:
/// relative, with no `..` or empty components.
pub fn safe_path(path: &str) -> bool {
    !path.is_empty()
        && !path.starts_with('/')
        && !path.contains('\\')
        && !path.contains(':')
        && path.split('/').all(|c| !c.is_empty() && c != "." && c != "..")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lock(name: &str) -> String {
        format!(
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n"
        )
    }

    #[test]
    fn round_trip_gives_identical_locks() {
        let locks = vec![
            ("Cargo.lock".to_string(), lock("root")),
            ("crates/a/Cargo.lock".to_string(), lock("a")),
            ("crates/b c/Cargo.lock".to_string(), lock("b")),
        ];
        let bytes: Vec<(String, Vec<u8>)> = locks.iter().map(|(p, t)| (p.clone(), t.clone().into_bytes())).collect();
        let note = String::from_utf8(assemble(&bytes)).unwrap();
        assert!(note.starts_with("# ---- Cargo.lock\n# This file"));
        assert_eq!(split(&note), locks);
    }

    #[test]
    fn assembly_matches_the_script_layout() {
        let note = assemble(&[("x/Cargo.lock".into(), b"a\nb\n".to_vec())]);
        assert_eq!(note, b"# ---- x/Cargo.lock\na\nb\n");
        assert!(assemble(&[]).is_empty());
    }

    #[test]
    fn split_ignores_a_preamble_and_keeps_crlf() {
        let got = split("stray\n# ---- Cargo.lock\r\none\r\n");
        assert_eq!(got, vec![("Cargo.lock".to_string(), "one\r\n".to_string())]);
    }

    #[test]
    fn unsafe_paths_are_refused() {
        assert!(safe_path("Cargo.lock"));
        assert!(safe_path("crates/a/Cargo.lock"));
        for bad in ["", "/etc/Cargo.lock", "../Cargo.lock", "a/../../b", "C:/x", "a//b", "a\\b", "./a"] {
            assert!(!safe_path(bad), "{bad}");
        }
    }
}
