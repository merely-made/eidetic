//! `house resolved record` and `show --write` against a fresh repository.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// A fresh directory under the system temp dir, removed on drop.
struct Tree(PathBuf);

impl Tree {
    fn new(name: &str) -> Tree {
        let dir = std::env::temp_dir().join(format!("house-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        Tree(dir)
    }

    fn write(&self, path: &str, text: &str) {
        let full = self.0.join(path);
        std::fs::create_dir_all(full.parent().unwrap()).unwrap();
        std::fs::write(full, text).unwrap();
    }

    fn read(&self, path: &str) -> String {
        std::fs::read_to_string(self.0.join(path)).unwrap()
    }
}

impl Drop for Tree {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn git(dir: &Path, args: &[&str]) -> Output {
    let hooks = dir.join(".no-hooks");
    let out = Command::new("git")
        .arg("-c")
        .arg(format!("core.hooksPath={}", hooks.display()))
        .args(["-c", "user.name=house test", "-c", "user.email=house@example.invalid", "-c", "commit.gpgsign=false"])
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(out.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&out.stderr));
    out
}

fn house(dir: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_house")).args(args).current_dir(dir).output().unwrap()
}

fn lock(name: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n"
    )
}

#[test]
fn record_then_show_write_restores_every_lock() {
    let t = Tree::new("record");
    let dir = &t.0;
    git(dir, &["init", "-q"]);
    t.write("Cargo.toml", "[workspace]\nmembers = [\"crates/a\"]\n");
    t.write("crates/a/Cargo.toml", "[package]\nname = \"a\"\n");
    t.write("crates/b/Cargo.toml", "[package]\nname = \"b\"\n");
    t.write("Cargo.lock", &lock("root"));
    t.write("crates/a/Cargo.lock", &lock("a"));
    // An untracked manifest's lock is not recorded.
    t.write("loose/Cargo.toml", "");
    t.write("loose/Cargo.lock", &lock("loose"));
    git(dir, &["add", "Cargo.toml", "crates/a/Cargo.toml", "crates/b/Cargo.toml"]);
    git(dir, &["commit", "-q", "-m", "first"]);

    let rec = house(dir, &["resolved", "record"]);
    assert!(rec.status.success() && rec.stderr.is_empty(), "{}", String::from_utf8_lossy(&rec.stderr));
    let note = String::from_utf8(git(dir, &["notes", "--ref=resolved", "show", "HEAD"]).stdout).unwrap();
    let want = format!("# ---- Cargo.lock\n{}# ---- crates/a/Cargo.lock\n{}", lock("root"), lock("a"));
    assert_eq!(note, want);

    let shown = house(dir, &["resolved", "show", "HEAD"]);
    assert!(shown.status.success());
    assert_eq!(String::from_utf8(shown.stdout).unwrap(), want);

    // Present locks are refused, and nothing is written.
    std::fs::remove_file(dir.join("crates/a/Cargo.lock")).unwrap();
    let refused = house(dir, &["resolved", "show", "HEAD", "--write"]);
    assert_eq!(refused.status.code(), Some(1));
    assert!(String::from_utf8_lossy(&refused.stderr).contains("Cargo.lock"));
    assert!(!dir.join("crates/a/Cargo.lock").exists());

    std::fs::remove_file(dir.join("Cargo.lock")).unwrap();
    let wrote = house(dir, &["resolved", "show", "HEAD", "--write"]);
    assert!(wrote.status.success(), "{}", String::from_utf8_lossy(&wrote.stderr));
    assert_eq!(t.read("Cargo.lock"), lock("root"));
    assert_eq!(t.read("crates/a/Cargo.lock"), lock("a"));

    t.write("Cargo.lock", "changed\n");
    assert!(house(dir, &["resolved", "show", "HEAD", "--write", "--force"]).status.success());
    assert_eq!(t.read("Cargo.lock"), lock("root"));

    // A second record replaces the note rather than failing.
    t.write("Cargo.lock", &lock("again"));
    assert!(house(dir, &["resolved", "record"]).status.success());
    let note = String::from_utf8(git(dir, &["notes", "--ref=resolved", "show", "HEAD"]).stdout).unwrap();
    assert!(note.starts_with(&format!("# ---- Cargo.lock\n{}", lock("again"))));
}

fn push(dir: &Path, remote: &str) -> Output {
    Command::new(env!("CARGO_BIN_EXE_house"))
        .args(["resolved", "push"])
        .env_remove("RESOLVED_NOTES_PUSH")
        .env("PRE_COMMIT_REMOTE_NAME", remote)
        .env("GIT_TERMINAL_PROMPT", "0")
        .current_dir(dir)
        .output()
        .unwrap()
}

#[test]
fn push_reports_a_failure_and_still_exits_zero() {
    let t = Tree::new("push");
    let dir = &t.0.join("work");
    std::fs::create_dir_all(dir).unwrap();
    git(dir, &["init", "-q"]);
    // Local config, so the children house runs see no hooks either.
    git(dir, &["config", "core.hooksPath", &dir.join(".no-hooks").display().to_string()]);
    std::fs::write(dir.join("Cargo.toml"), "").unwrap();
    std::fs::write(dir.join("Cargo.lock"), lock("root")).unwrap();
    git(dir, &["add", "Cargo.toml"]);
    git(dir, &["commit", "-q", "-m", "first"]);

    // Positive control: a real remote takes the notes without a word.
    let bare = t.0.join("remote.git");
    git(&t.0, &["init", "-q", "--bare", bare.to_str().unwrap()]);
    git(dir, &["remote", "add", "good", bare.to_str().unwrap()]);
    let ok = push(dir, "good");
    assert!(ok.status.success());
    assert!(ok.stderr.is_empty(), "{}", String::from_utf8_lossy(&ok.stderr));
    // Only the notes ref went over, so name the commit by its id.
    let head = String::from_utf8(git(dir, &["rev-parse", "HEAD"]).stdout).unwrap();
    let sent = git(&bare, &["notes", "--ref=resolved", "show", head.trim()]);
    assert!(String::from_utf8(sent.stdout).unwrap().starts_with("# ---- Cargo.lock\n"));

    let bad = push(dir, "nowhere");
    assert!(bad.status.success());
    let err = String::from_utf8(bad.stderr).unwrap();
    let lines: Vec<&str> = err.lines().collect();
    assert_eq!(lines.len(), 2, "{err}");
    assert!(lines[0].starts_with("house resolved push: could not fetch refs/notes/resolved from nowhere: "), "{err}");
    assert!(lines[1].starts_with("house resolved push: could not push refs/notes/resolved to nowhere: "), "{err}");
    assert!(lines[1].len() > "house resolved push: could not push refs/notes/resolved to nowhere: ".len());
}

#[test]
fn record_outside_a_repository_and_push_when_pushing_exit_zero() {
    let t = Tree::new("outside");
    // GIT_DIR pointing nowhere keeps an enclosing repository out of reach.
    let record = Command::new(env!("CARGO_BIN_EXE_house"))
        .args(["resolved", "record"])
        .env("GIT_DIR", t.0.join("no-such-git"))
        .current_dir(&t.0)
        .output()
        .unwrap();
    assert!(record.status.success() && record.stderr.is_empty());
    let push = Command::new(env!("CARGO_BIN_EXE_house"))
        .args(["resolved", "push"])
        .env("RESOLVED_NOTES_PUSH", "1")
        .current_dir(&t.0)
        .output()
        .unwrap();
    assert!(push.status.success());
    assert_eq!(house(&t.0, &["resolved", "frob"]).status.code(), Some(2));
    assert_eq!(house(&t.0, &["resolved", "show"]).status.code(), Some(2));
}
